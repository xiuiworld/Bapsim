"""Validate installation settings and render a build-time header, never collect data."""
import argparse
import json
from pathlib import Path
import re

from tools.a07_edge.observations import Calibration


def load_profile(path):
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if set(data) != {'timer_trusted', 'calibration'} or type(data['timer_trusted']) is not bool:
        raise ValueError('profile requires calibration and an explicit timer_trusted boolean')
    cal = Calibration(**data['calibration'])
    cal.validate()
    if not re.fullmatch(r'[A-Za-z0-9_.-]{1,60}', cal.version):
        raise ValueError('calibration version must be a short safe identifier')
    return data, cal


def render_profile(path, destination):
    data, cal = load_profile(path)
    numbers = lambda values: ','.join(format(float(v), '.17g') for v in values)
    fields = [cal.adc_max, cal.series_ohms, cal.ntc_r25, cal.ntc_beta, cal.offset_c]
    header = ('// Generated by firmware.a08.profile from installation settings.\n'
              '#pragma once\n#include "a07/preprocess.hpp"\nnamespace a08 {\n'
              f'constexpr uint8_t TRUSTED_LED_MASK = {15 if data["timer_trusted"] else 7};\n'
              'constexpr a07::Calibration CAL = {{'+numbers(cal.led_off)+'},{'+numbers(cal.led_on)+'},'+
              numbers(fields)+','+str(cal.ntc_to_ground).lower()+','+
              numbers([cal.warm_white_gain, cal.white_reference])+'};\n'
              f'constexpr const char *CAL_VERSION = "{cal.version}";\n}}\n')
    Path(destination).write_text(header, encoding='utf-8')
    return data


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--profile', required=True)
    p.add_argument('--output', required=True)
    args = p.parse_args()
    render_profile(args.profile, args.output)
