"""Build one installable sensor.py from the tested raw codec and HA platform."""
from pathlib import Path


def main():
    root = Path(__file__).resolve().parent
    validator = root.joinpath("validate_snapshot.py").read_text(encoding="utf-8").split("def main():")[0]
    wire = root.joinpath("wire.py").read_text(encoding="utf-8").replace("from .validate_snapshot import SIGNALS, validate", "# Validator is bundled above.")
    platform = root.joinpath("ha_sensor.py").read_text(encoding="utf-8")
    output = root / 'ha_bundle' / 'sensor.py'
    output.parent.mkdir(exist_ok=True)
    output.write_text('# Generated by tools/a05_contract/build_ha_bundle.py; do not hand edit.\n' + validator + '\n' + wire + '\n' + platform, encoding='utf-8')
    compile(output.read_text(encoding='utf-8'), str(output), 'exec')
    print(output)


if __name__ == '__main__':
    main()
